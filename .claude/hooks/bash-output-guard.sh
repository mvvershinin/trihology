#!/bin/bash
# PreToolUse: Bash — предохранитель расхода контекста.
#
# Замер 14.09.2026 — разбор в `docs/CONTEXT-COST.md`.
#
# ⚠️ Числа про долю `Bash` померены на СОСЕДНЕМ проекте (`/home/mvv/Projects/trade`):
# выдача `Bash` — 78 % всего, что инструменты кладут в контекст. У нас своей
# истории сессий не сохранилось (замер 1 в документе), поэтому свой профиль
# неизвестен и эта доля у нас НЕ ПРОВЕРЕНА.
#
# Что померено на нашем дереве: порог 20 000 байт — 68-й персентиль, отсекает
# треть файлов, в которых лежит 70 % всех байтов (замер 3).
#
# Довод, не зависящий от проекта: контекст перечитывается каждым следующим
# запросом, поэтому лишний дамп оплачивается не один раз, а столько раз,
# сколько осталось запросов в сессии.
#
# ⚠️ Проверки на ПОВТОРНОЕ чтение здесь нет, и это решение по замеру, а не недоделка.
# Первая редакция такую проверку имела: файл, уже читавшийся в сессии и с тех пор
# не менявшийся, блокировался. Замер (снова НА СОСЕДНЕМ проекте) показал, что ловить
# нечего — дословно совпадающих выдач среди 1731 оказалось 10 штук, 0,2 % объёма.
# А все 226 «повторных открытий» были РАЗНЫМИ кусками одного файла, то есть новым
# содержимым. У нас этот замер повторить не на чем: истории сессий нет.
# Проверка запрещала бы ровно то, что сама же советует в тексте отказа. Сторож,
# срабатывающий только ложно, хуже отсутствующего.
#
# Блокировка — exit 2 со stderr: работает независимо от версии схемы JSON у хуков.
#
# Предохранитель, который при собственной поломке молча пропускает всё, — хуже
# отсутствующего. Поэтому разбор входа дублирован, а о невозможности разобрать
# хук говорит вслух (правило 13: молчание — самостоятельный дефект).

set -uo pipefail

INPUT=$(cat)

if command -v jq >/dev/null 2>&1; then
    CMD=$(printf '%s' "$INPUT" | jq -r '.tool_input.command // empty' 2>/dev/null)
    SID=$(printf '%s' "$INPUT" | jq -r '.session_id // "nosession"' 2>/dev/null)
elif command -v python3 >/dev/null 2>&1; then
    VHOD=$(printf '%s' "$INPUT" | python3 -c \
'import json,sys
d=json.load(sys.stdin)
print(d.get("session_id","nosession"))
print(d.get("tool_input",{}).get("command","").replace("\n"," "))' 2>/dev/null)
    SID=$(printf '%s\n' "$VHOD" | head -n 1)
    CMD=$(printf '%s\n' "$VHOD" | tail -n +2)
else
    printf '⚠️ bash-output-guard: нет ни jq, ни python3 — предохранитель расхода НЕ РАБОТАЕТ.\n' >&2
    exit 0
fi

[ -n "${CMD:-}" ] || exit 0

# Перенаправление stderr выдачу НЕ уводит: `cat файл 2>/dev/null` печатает файл
# в контекст целиком. Снимаем такие хвосты до проверки на запись, иначе привычное
# `2>&1` отключало предохранитель — проверено 14.09.2026 на живом пути: из первых
# четырёх команд сессии три несли `2>&1` или `2>/dev/null` и проходили насквозь.
CMD=$(printf '%s' "$CMD" | sed -E 's/2>&1//g; s/2>>?[[:space:]]*[^[:space:]|;&]+//g')

# ⚠️ Здесь НЕТ проверки «есть в команде `>` или heredoc — значит выходим».
# Она была и оказалась дефектом того же рода, что и хвост stderr: один `>` где
# угодно снимал проверку со ВСЕХ чтений в команде. Проверено 14.09.2026 —
# `cat большой_файл; echo done > /tmp/x` проходил насквозь, как и
# `cat большой_файл && python3 - <<PY`. А heredoc здесь основной способ писать
# файлы, то есть сторож был бы выключен в половине работы.
# Запись распознаётся ПО ЗВЕНУ команды — в разборе на Python ниже.

# Порог проверен на нашем дереве 14.09.2026 (замер 3): 68-й персентиль из 77 файлов,
# выше него треть файлов и 70 % всех байтов. Ниже (15 000) — плюс 7 пунктов байтов
# ценой пяти лишних отказов; выше (25 000) — минус 19 пунктов. Оставлен как есть.
POROG_BYTES=20000          # больше этого дамп без ограничителя не пропускаем
# При наличии python3 ограничитель ищется по конвейерам в разборе ниже.
# Грубый поиск по всей строке остаётся только запасным, в ветке без python3.
OGRANICHEN=0

deny() {
    printf '⛔ ПРЕДОХРАНИТЕЛЬ РАСХОДА КОНТЕКСТА\n\n%s\n\n%s\n' "$1" \
"Контекст перечитывается каждым следующим запросом сессии, поэтому дамп
оплачивается столько раз, сколько запросов осталось. Порог, выход из-под
проверки и замер — docs/CONTEXT-COST.md" >&2
    exit 2
}

# Кандидаты на чтение. Разбор идёт по звеньям команды: звено считается чтением,
# если начинается с читающей команды, и тогда из него берутся все существующие файлы.
#
# ⚠️ Регулярка `(cat|sed -n[^|]*)[[:space:]]+(…)` первой редакции ловила `cat файл`
# и пропускала `sed -n '1,5p' файл` — жадная часть съедала имя файла целиком.
# Сторож молча не видел половины случаев, ради которых поставлен.
if command -v python3 >/dev/null 2>&1; then
    RAZBOR=$(printf '%s' "$CMD" | python3 -c '
import os,re,shlex,sys
CHITAET={"cat","sed","head","tail","less","more","nl","tac"}
OGRANICHITELI={"head","tail","wc","grep","rg","jq","sort","uniq"}
cmd=sys.stdin.read()

# Тело heredoc — записываемый текст, а не команды. Без вырезания документ,
# внутри которого написано `cat файл`, разбирался бы как чтение этого файла.
stroki=cmd.split("\n"); chistye=[]; i=0
while i<len(stroki):
    chistye.append(stroki[i])
    m=re.search(r"<<-?\s*[\"\x27]?([A-Za-z_][A-Za-z0-9_]*)[\"\x27]?", stroki[i])
    if m:
        marker=m.group(1); i+=1
        while i<len(stroki) and stroki[i].strip()!=marker: i+=1
    i+=1
cmd="\n".join(chistye)

out=[]
neyasno=0
# Разбор по утверждениям, внутри — по звеньям конвейера. Перенаправление делает
# утверждение записью; ограничитель в любом звене сужает весь конвейер.
for utv in re.split(r";|&&|\|\||\n", cmd):
    if ">" in utv or "<<" in utv: continue
    zvenya=[]
    for z in utv.split("|"):
        try: zvenya.append(shlex.split(z))
        except ValueError: zvenya.append(z.split())
    ogr=0
    for sl in zvenya:
        if sl and os.path.basename(sl[0]) in OGRANICHITELI: ogr=1
    # Узкий диапазон sed — это ограничитель, а не дамп: sed -n "10,20p" даёт 11 строк.
    for a,b in re.findall(r"sed\s+-n\s+[\x27\"]?(\d+),(\d+)p", utv):
        if int(b)-int(a) <= 500: ogr=1
    if ogr: continue
    for sl in zvenya:
        if not sl: continue
        i=0
        while i<len(sl) and (sl[i] in ("cd","sudo","time","env") or "=" in sl[i]):
            i+=2 if sl[i]=="cd" else 1
        if i>=len(sl) or os.path.basename(sl[i]) not in CHITAET: continue
        for s in sl[i+1:]:
            if s.startswith("-"): continue
            # Хук видит команду ДО подстановки переменных шелла: `cat $F` приходит
            # так и есть. Развернуть нельзя (это eval), значит размер файла неизвестен.
            if "$" in s or "`" in s: neyasno=1; continue
            if os.path.isfile(s): out.append(s)
print("NEYASNO=%d" % neyasno)
print("\n".join(dict.fromkeys(out)))
' 2>/dev/null)
    case "$RAZBOR" in *NEYASNO=1*) NEYASNO=1 ;; *) NEYASNO=0 ;; esac
    FILES=$(printf '%s\n' "$RAZBOR" | tail -n +2)
else
    NEYASNO=0
    # Грубый разбор звеньев не различает, поэтому здесь запись и ограничитель
    # проверяются по всей строке: грубее, зато без ложных отказов на записи.
    case "$CMD" in
        *'<<'*|*'>'*) exit 0 ;;
    esac
    case "$CMD" in
        *'head'*|*'tail'*|*'wc '*|*'grep'*|*'| jq'*) OGRANICHEN=1 ;;
    esac
    FILES=$(printf '%s\n' "$CMD" | grep -oE 'cat[[:space:]]+([^|;&[:space:]]+)' 2>/dev/null \
        | awk '{print $NF}' | sort -u)
    printf '⚠️ bash-output-guard: нет python3 — разбор упрощён, sed/head не проверяются.\n' >&2
fi

# Файл назван переменной — размер неизвестен, значит и потолок выдачи неизвестен.
# Дыру нашла встречная проверка сессии life/.mounted 14.09.2026: `cat $F` проходил
# насквозь, потому что литерального файла с именем "$F" на диске нет и звено молча
# отбрасывалось. Развернуть переменную предохранитель не может, но может потребовать
# ограничитель — тогда потолок выдачи известен независимо от того, что за файл.
if [ "${NEYASNO:-0}" -eq 1 ] && [ "$OGRANICHEN" -eq 0 ]; then
    deny "Файл назван переменной — предохранитель не видит, что читается и какого размера.
Развернуть переменную он не может: это было бы исполнением команды.

Поставь ограничитель, и потолок выдачи станет известен независимо от файла:
| head -n 50, или диапазон sed -n '1,50p', или grep по признаку.
Если файл действительно нужен целиком — скажи это явно: | head -n 100000."
fi

# Через here-string, а не через конвейер: конвейер увёл бы цикл в подоболочку,
# и `exit 2` из deny() закрыл бы только её — предохранитель молча пропустил бы всё.
while IFS= read -r F; do
    case "$F" in -*|'') continue ;; esac
    [ -f "$F" ] || continue
    SZ=$(stat -c %s "$F" 2>/dev/null) || continue
    MT=$(stat -c %Y "$F" 2>/dev/null) || continue

    # Случай 1: дамп крупного файла без ограничителя.
    if [ "$OGRANICHEN" -eq 0 ] && [ "$SZ" -gt "$POROG_BYTES" ]; then
        deny "Файл $F — $SZ байт, читается целиком без ограничителя.

Целиком он всё равно НЕ ПРИДЁТ: Claude Code режет выдачу Bash примерно на
18 000 символах и подменяет её заглушкой <persisted-output> со ссылкой на файл.
То есть ты получишь обрывок вместо содержимого, а контекст всё равно потяжелеет
на несколько тысяч токенов — и они останутся там до конца сессии.

Возьми нужное: | head -n 50, или диапазон sed -n '1,50p', или grep по признаку.
Нужен объём, а не содержимое — wc -l.
Если обрывок и правда устроит — скажи это явно: | head -n 100000."
    fi

done <<< "$FILES"

exit 0
